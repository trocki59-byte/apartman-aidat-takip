import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { createApplication } from '../../src/server.js';
import { inject } from '../inject.js';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

test('yönetici kurulumdan rapora tüm mali akışı tamamlar ve mobil menü çalışır', async t => {
  const app = createApplication({ dbPath: ':memory:', passwordRequired: true });
  t.after(() => app.store.close());
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1024 }, locale: 'tr-TR' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await context.route('http://127.0.0.1/**', async route => {
    const request = route.request(), url = new URL(request.url());
    const headers = await request.allHeaders();
    const result = await inject(app.server, { path: url.pathname, method: request.method(), headers: { ...headers, Host: '127.0.0.1' }, payload: request.postData() || '' });
    const responseHeaders = Object.fromEntries(result.headers.entries());
    delete responseHeaders['transfer-encoding']; delete responseHeaders['connection'];
    await route.fulfill({ status: result.status, headers: responseHeaders, body: result.body });
  });
  await page.goto('http://127.0.0.1/');
  await page.getByRole('heading', { name: 'İlk kuruluma hoş geldiniz' }).waitFor();
  await page.getByLabel('Yönetici parolası', { exact: true }).fill('Guvenli-Parola-2026!');
  await page.getByLabel('Parolayı tekrar girin', { exact: true }).fill('Guvenli-Parola-2026!');
  await page.getByRole('button', { name: 'Parola Oluştur ve Başla' }).click();
  await page.getByRole('heading', { name: 'Genel Bakış', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Daireler', exact: true }).click();
  await page.getByRole('button', { name: 'Daire Ekle', exact: true }).click();
  await page.getByLabel('Daire numarası', { exact: true }).fill('1');
  await page.getByLabel('Malik adı soyadı').fill('Ayşe Yılmaz');
  await page.getByLabel('Sakin / kiracı adı soyadı').fill('Mehmet Kaya');
  await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
  await page.getByRole('cell', { name: 'Daire 1', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Aidatlar', exact: true }).click();
  await page.getByRole('button', { name: 'Aidat Oluştur', exact: true }).first().click();
  await page.getByRole('button', { name: 'Aidatları Oluştur' }).click();
  await page.getByRole('cell', { name: 'Aylık aidat', exact: false }).waitFor();
  await page.getByRole('button', { name: 'Bu borca tahsilat', exact: true }).click();
  await page.getByLabel('Tahsilat tutarı (₺)').fill('750,50');
  await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
  await page.getByText('Kısmi ödeme', { exact: true }).waitFor();
  assert.equal(app.store.snapshot().units[0].debtCents, 124950);
  await page.getByRole('link', { name: 'Giderler', exact: true }).click();
  await page.getByRole('button', { name: 'Gider Ekle', exact: true }).first().click();
  await page.getByLabel('Gider tutarı (₺)').fill('250,25');
  await page.getByLabel('Açıklama', { exact: true }).fill('Ortak alan aydınlatması');
  await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
  await page.getByRole('cell', { name: 'Ortak alan aydınlatması' }).waitFor();
  assert.equal(app.store.snapshot().accounts[0].balanceCents, 50025);
  await page.getByRole('link', { name: 'Tahsilatlar', exact: true }).click();
  await page.getByRole('button', { name: 'Makbuzu görüntüle' }).click();
  await page.getByRole('heading', { name: 'Tahsilat Makbuzu' }).waitFor();
  await page.getByRole('button', { name: 'Kapat', exact: true }).click();
  await page.getByRole('link', { name: 'Raporlar', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'CSV İndir' }).click();
  const download = await downloadPromise; assert.match(download.suggestedFilename(), /\.csv$/);
  await page.getByRole('link', { name: 'Genel Bakış', exact: true }).click();
  await page.reload();
  await page.getByRole('heading', { name: 'Genel Bakış', exact: true }).waitFor();
  mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Menüyü aç' }).click();
  await page.getByRole('link', { name: 'Daireler', exact: true }).click();
  await page.getByRole('heading', { name: 'Daireler', exact: true }).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: 'test-results/units-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
});
